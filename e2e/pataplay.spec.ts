import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
async function start(page:Page) {
 await page.goto('/');
 await page.getByRole('button',{name:'Começar transformação'}).click();
 await page.getByLabel('Nome do pet').fill('Thor');
 await page.getByRole('button',{name:'Entrar no estúdio'}).click();
 await expect(page.getByRole('heading',{name:/Hoje é dia de brilhar/})).toBeVisible();
}
test('Thor: personalização, carrinho, checkout, confirmação e recarga',async({page},info)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.screenshot({path:info.outputPath('01-home.png'),fullPage:true,animations:'disabled'});
 await page.getByRole('button',{name:'Começar transformação'}).click();
 await page.getByLabel('Nome do pet').fill('Thor');
 await page.screenshot({path:info.outputPath('02-pets.png'),fullPage:true,animations:'disabled'});
 await page.getByRole('button',{name:'Entrar no estúdio'}).click();
 await page.getByRole('button',{name:/Tosa bebê/}).click();
 await expect(page.locator('.studio-dog svg.dog-illustration')).toHaveAttribute('data-cut','puppy');
 await page.getByRole('button',{name:'Antes e depois'}).click();
 await expect(page.locator('.studio-dog svg.dog-illustration')).toHaveAttribute('data-cut','bath');
 await page.getByRole('button',{name:'Ver depois'}).click();
 await page.getByRole('tab',{name:'Acessórios'}).click();
 await page.getByRole('button',{name:/^Bandana/}).click();
 await page.getByRole('button',{name:'Rosa',exact:true}).click();
 await expect(page.locator('.studio-dog [data-accessory="bandana"] path').first()).toHaveAttribute('fill','#ec7899');
 await page.getByRole('tab',{name:'Essências'}).click();
 await page.getByRole('button',{name:/^Lavanda/}).click();
 await expect(page.getByTestId('studio-total')).toContainText('122,00');
 await page.screenshot({path:info.outputPath('03-studio.png'),fullPage:true,animations:'disabled'});
 await page.reload();
 await expect(page.getByTestId('studio-total')).toContainText('122,00');
 await expect(page.locator('.studio-dog [data-scent="lavender"]')).toHaveCount(1);
 await page.getByRole('tab',{name:'Essências'}).click();
 await page.getByRole('button',{name:'Ver transformação'}).click();
 await expect(page.getByRole('heading',{name:/Uau! Thor/})).toBeVisible();
 await page.getByRole('button',{name:'Continuar para a lojinha'}).click();
 await page.getByRole('button',{name:'Adicionar Bolinha interativa',exact:true}).click();
 await page.reload();
 await expect(page.getByLabel('Quantidade de Bolinha interativa')).toHaveText('1');
 await page.getByRole('button',{name:'Adicionar uma unidade de Bolinha interativa',exact:true}).click();
 await expect(page.getByLabel('Quantidade de Bolinha interativa')).toHaveText('2');
 await page.getByRole('button',{name:'Remover uma unidade de Bolinha interativa',exact:true}).click();
 await page.screenshot({path:info.outputPath('04-shop.png'),fullPage:true,animations:'disabled'});
 await page.getByRole('button',{name:'Continuar',exact:true}).click();
 await expect(page.getByTestId('summary-total')).toContainText('146,90');
 await page.getByRole('button',{name:'Finalizar pedido fictício'}).click();
 await expect(page.getByText('Informe seu nome e sobrenome.')).toBeVisible();
 await page.getByLabel('Nome completo').fill('Pessoa de Teste');
 await page.getByLabel('Telefone com DDD').fill('11999999999');
 await page.getByLabel('E-mail',{exact:true}).fill('teste@example.com');
 await page.getByRole('radio',{name:/Cartão/}).check();
 await expect(page.locator('input[name="cardNumber"]')).toHaveCount(0);
 await page.getByRole('button',{name:'Finalizar pedido fictício'}).click();
 await expect(page.getByRole('heading',{name:/Um dia de carinho/})).toBeVisible();
 const orderId=await page.locator('.order-id').textContent();
 await page.reload();
 await expect(page.locator('.order-id')).toHaveText(orderId!);
 await expect(page.locator('.order-receipt .summary-total')).toContainText('146,90');
 await page.screenshot({path:info.outputPath('05-success.png'),fullPage:true,animations:'disabled'});
 await page.getByRole('button',{name:'Iniciar novo pedido'}).click();
 await page.getByRole('button',{name:'Meus pedidos',exact:true}).click();
 await expect(page.locator('.history-card')).toHaveCount(1);
 await page.locator('.history-card').click();
 await expect(page.locator('.order-id')).toHaveText(orderId!);
 expect(errors).toEqual([]);
});
