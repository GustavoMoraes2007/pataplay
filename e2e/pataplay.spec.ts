test('navegação para trás preserva dados e não há transbordamento horizontal',async({page})=>{
 await start(page);
 await page.getByRole('button',{name:/Tosa bebê/}).click();
 await page.goBack();
 await expect(page.getByLabel('Nome do pet')).toHaveValue('Thor');
 await page.getByRole('button',{name:'Entrar no estúdio'}).click();
 await expect(page.locator('.studio-dog svg.dog-illustration')).toHaveAttribute('data-cut','puppy');
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 expect(overflow).toBe(false);
});
test('histórico vazio e armazenamento corrompido têm recuperação',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'Meus pedidos',exact:true}).click();
 await expect(page.getByText('A primeira transformação ainda vem aí.')).toBeVisible();
 await page.evaluate(()=>localStorage.setItem('pataplay:v1','{broken'));
 await page.reload();
 await expect(page.getByRole('alert')).toContainText('Não foi possível recuperar');
 await page.getByRole('button',{name:'Começar transformação'}).click();
 await expect(page.getByRole('button',{name:'Entrar no estúdio'})).toBeDisabled();
});
